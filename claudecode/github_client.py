#!/usr/bin/env python3
"""Unified GitHub API client for all GitHub operations.

This module provides a single, consolidated GitHub client that handles:
- Authentication (token-based, supports GitHub Enterprise)
- PR data retrieval
- PR commenting and reviews
- Diff fetching with filtering

All other modules should use this client instead of implementing their own.
"""

import os
import re
import sys
from typing import Any, Dict, List, Optional

import requests

from claudecode.logger import get_logger

logger = get_logger(__name__)


class GitHubClientError(Exception):
    """Base exception for GitHub client errors."""
    pass


class GitHubAuthenticationError(GitHubClientError):
    """Raised when authentication fails or token is missing."""
    pass


class GitHubAPIError(GitHubClientError):
    """Raised when a GitHub API call fails."""
    pass


class GitHubClient:
    """Unified GitHub API client supporting both github.com and GitHub Enterprise.

    This client consolidates all GitHub API interactions into a single class,
    eliminating code duplication between different modules.

    Environment Variables:
        GITHUB_TOKEN: Required. Personal access token or GitHub Actions token.
        GITHUB_API_URL: Optional. API URL for GitHub Enterprise instances.
            Defaults to https://api.github.com for public GitHub.

    Example:
        >>> client = GitHubClient()
        >>> pr_data = client.get_pr_data("owner/repo", 123)
        >>> diff = client.get_pr_diff("owner/repo", 123)
    """

    # Generated file markers to filter from diffs
    GENERATED_FILE_MARKERS = (
        '@generated by',
        '@generated',
        'Code generated by OpenAPI Generator',
        'Code generated by protoc-gen-go',
    )

    def __init__(
        self,
        token: Optional[str] = None,
        api_url: Optional[str] = None,
        excluded_directories: Optional[List[str]] = None,
    ):
        """Initialize the GitHub client.

        Args:
            token: GitHub token. If None, reads from GITHUB_TOKEN env var.
            api_url: GitHub API URL. If None, reads from GITHUB_API_URL env var,
                     defaulting to https://api.github.com.
            excluded_directories: List of directory patterns to exclude from results.
                                  If None, reads from EXCLUDE_DIRECTORIES env var.

        Raises:
            GitHubAuthenticationError: If no token is provided or found.
        """
        # Get token
        self.token = token or os.environ.get('GITHUB_TOKEN')
        if not self.token:
            raise GitHubAuthenticationError(
                "GITHUB_TOKEN environment variable required. "
                "Please set it to a valid GitHub personal access token or use the "
                "automatic token provided in GitHub Actions."
            )

        # Get API URL (supports GitHub Enterprise)
        default_api_url = 'https://api.github.com'
        self.api_base_url = (api_url or os.environ.get('GITHUB_API_URL', default_api_url)).rstrip('/')

        if self.api_base_url != default_api_url:
            logger.info(f"Using GitHub Enterprise API: {self.api_base_url}")

        # Parse excluded directories
        if excluded_directories is not None:
            self.excluded_directories = excluded_directories
        else:
            exclude_env = os.environ.get('EXCLUDE_DIRECTORIES', '')
            self.excluded_directories = [
                d.strip() for d in exclude_env.split(',') if d.strip()
            ] if exclude_env else []

        if self.excluded_directories:
            logger.debug(f"Excluded directories: {self.excluded_directories}")

        # Set up request headers
        self.headers = {
            'Authorization': f'Bearer {self.token}',
            'Accept': 'application/vnd.github.v3+json',
            'X-GitHub-Api-Version': '2022-11-28',
        }

    @property
    def host(self) -> str:
        """Get the GitHub host from the API URL.

        Returns:
            The hostname (e.g., 'github.com' or 'github.mycompany.com').
        """
        from urllib.parse import urlparse
        parsed = urlparse(self.api_base_url)
        hostname = parsed.hostname or 'github.com'

        # Handle api.github.com -> github.com
        if hostname == 'api.github.com':
            return 'github.com'

        return hostname

    def _request(
        self,
        method: str,
        endpoint: str,
        headers: Optional[Dict[str, str]] = None,
        **kwargs,
    ) -> requests.Response:
        """Make an API request with error handling.

        Args:
            method: HTTP method (GET, POST, etc.)
            endpoint: API endpoint (e.g., /repos/owner/repo/pulls/123)
            headers: Optional headers to override defaults
            **kwargs: Additional arguments passed to requests

        Returns:
            Response object

        Raises:
            GitHubAPIError: If the request fails
        """
        url = f"{self.api_base_url}{endpoint}"
        request_headers = dict(self.headers)
        if headers:
            request_headers.update(headers)

        try:
            response = requests.request(method, url, headers=request_headers, **kwargs)
            response.raise_for_status()
            return response
        except requests.HTTPError as e:
            # Don't include full URL in error (may contain tokens in some edge cases)
            raise GitHubAPIError(
                f"GitHub API error on {method} {endpoint}: {e.response.status_code} - {e.response.reason}"
            ) from e
        except requests.RequestException as e:
            raise GitHubAPIError(f"GitHub API request failed: {e}") from e

    def _get(self, endpoint: str, **kwargs) -> Any:
        """Make a GET request and return JSON response."""
        return self._request('GET', endpoint, **kwargs).json()

    def _post(self, endpoint: str, data: Dict[str, Any], **kwargs) -> Any:
        """Make a POST request and return JSON response."""
        return self._request('POST', endpoint, json=data, **kwargs).json()

    def _is_excluded_path(self, filepath: str) -> bool:
        """Check if a file path should be excluded.

        Args:
            filepath: Path to check

        Returns:
            True if the file should be excluded
        """
        for excluded_dir in self.excluded_directories:
            # Normalize (remove leading ./)
            normalized = excluded_dir.lstrip('./')

            # Check if file starts with excluded directory
            if filepath.startswith(f"{excluded_dir}/") or filepath.startswith(f"{normalized}/"):
                return True

            # Check if excluded directory appears in the path
            if f"/{normalized}/" in filepath:
                return True

        return False

    def _is_generated_content(self, content: str) -> bool:
        """Check if content appears to be generated code.

        Args:
            content: Content to check

        Returns:
            True if the content appears to be generated
        """
        return any(marker in content for marker in self.GENERATED_FILE_MARKERS)

    def _filter_diff(self, diff_text: str) -> str:
        """Filter generated files and excluded directories from diff.

        Args:
            diff_text: Raw diff text

        Returns:
            Filtered diff text
        """
        # Split by diff sections
        sections = re.split(r'(?=^diff --git)', diff_text, flags=re.MULTILINE)
        filtered = []

        for section in sections:
            if not section.strip():
                continue

            # Skip generated files
            if self._is_generated_content(section):
                continue

            # Extract filename and check exclusions
            match = re.match(r'^diff --git a/(.*?) b/', section)
            if match:
                filename = match.group(1)
                if self._is_excluded_path(filename):
                    logger.debug(f"Filtering excluded file from diff: {filename}")
                    continue

            filtered.append(section)

        return ''.join(filtered)

    # -------------------------------------------------------------------------
    # PR Data Methods
    # -------------------------------------------------------------------------

    def get_pr(self, owner: str, repo: str, pr_number: int) -> Dict[str, Any]:
        """Get PR metadata.

        Args:
            owner: Repository owner
            repo: Repository name
            pr_number: Pull request number

        Returns:
            PR data dictionary
        """
        return self._get(f"/repos/{owner}/{repo}/pulls/{pr_number}")

    def get_pr_files(
        self,
        owner: str,
        repo: str,
        pr_number: int,
        per_page: int = 100,
    ) -> List[Dict[str, Any]]:
        """Get files changed in a PR.

        Args:
            owner: Repository owner
            repo: Repository name
            pr_number: Pull request number
            per_page: Number of files per page (max 100)

        Returns:
            List of file dictionaries
        """
        files = self._get(f"/repos/{owner}/{repo}/pulls/{pr_number}/files?per_page={per_page}")

        # Filter excluded files
        return [f for f in files if not self._is_excluded_path(f['filename'])]

    def get_pr_data(self, repo_full_name: str, pr_number: int) -> Dict[str, Any]:
        """Get comprehensive PR data including files.

        This is a convenience method that combines PR metadata and files
        into a single structured result.

        Args:
            repo_full_name: Repository in "owner/repo" format
            pr_number: Pull request number

        Returns:
            Dictionary with PR data and files
        """
        if '/' not in repo_full_name:
            raise ValueError(f"Invalid repository format: {repo_full_name}. Expected 'owner/repo'.")

        owner, repo = repo_full_name.split('/', 1)

        pr = self.get_pr(owner, repo, pr_number)
        files = self.get_pr_files(owner, repo, pr_number)

        return {
            'number': pr['number'],
            'title': pr['title'],
            'body': pr.get('body') or '',
            'user': pr['user']['login'],
            'created_at': pr['created_at'],
            'updated_at': pr['updated_at'],
            'state': pr['state'],
            'head': {
                'ref': pr['head']['ref'],
                'sha': pr['head']['sha'],
                'repo': {
                    'full_name': (
                        pr['head']['repo']['full_name']
                        if pr['head']['repo']
                        else repo_full_name
                    )
                },
            },
            'base': {
                'ref': pr['base']['ref'],
                'sha': pr['base']['sha'],
            },
            'files': [
                {
                    'filename': f['filename'],
                    'status': f['status'],
                    'additions': f['additions'],
                    'deletions': f['deletions'],
                    'changes': f['changes'],
                    'patch': f.get('patch', ''),
                }
                for f in files
            ],
            'additions': pr['additions'],
            'deletions': pr['deletions'],
            'changed_files': pr['changed_files'],
        }

    def get_pr_diff(self, repo_full_name: str, pr_number: int) -> str:
        """Get PR diff in unified format.

        Args:
            repo_full_name: Repository in "owner/repo" format
            pr_number: Pull request number

        Returns:
            Filtered diff text
        """
        if '/' not in repo_full_name:
            raise ValueError(f"Invalid repository format: {repo_full_name}. Expected 'owner/repo'.")

        owner, repo = repo_full_name.split('/', 1)

        response = self._request(
            'GET',
            f"/repos/{owner}/{repo}/pulls/{pr_number}",
            headers={'Accept': 'application/vnd.github.diff'},
        )

        return self._filter_diff(response.text)

    # -------------------------------------------------------------------------
    # PR Comment Methods
    # -------------------------------------------------------------------------

    def get_pr_comments(self, owner: str, repo: str, pr_number: int) -> List[Dict[str, Any]]:
        """Get review comments on a PR.

        Args:
            owner: Repository owner
            repo: Repository name
            pr_number: Pull request number

        Returns:
            List of comment dictionaries
        """
        return self._get(f"/repos/{owner}/{repo}/pulls/{pr_number}/comments")

    def get_review_comments(
        self,
        owner: str,
        repo: str,
        pr_number: int,
        review_id: int,
    ) -> List[Dict[str, Any]]:
        """Get comments from a specific review.

        Args:
            owner: Repository owner
            repo: Repository name
            pr_number: Pull request number
            review_id: Review ID

        Returns:
            List of comment dictionaries
        """
        try:
            return self._get(f"/repos/{owner}/{repo}/pulls/{pr_number}/reviews/{review_id}/comments")
        except GitHubAPIError as e:
            logger.warning(f"Failed to get review comments: {e}")
            return []

    def create_review(
        self,
        owner: str,
        repo: str,
        pr_number: int,
        commit_sha: str,
        comments: List[Dict[str, Any]],
        event: str = 'COMMENT',
    ) -> Optional[Dict[str, Any]]:
        """Create a PR review with inline comments.

        Args:
            owner: Repository owner
            repo: Repository name
            pr_number: Pull request number
            commit_sha: SHA of the commit to comment on
            comments: List of comment dictionaries with path, line, side, body
            event: Review event type (COMMENT, APPROVE, REQUEST_CHANGES)

        Returns:
            Review response if successful, None otherwise
        """
        try:
            return self._post(
                f"/repos/{owner}/{repo}/pulls/{pr_number}/reviews",
                {
                    'commit_id': commit_sha,
                    'event': event,
                    'comments': comments,
                },
            )
        except GitHubAPIError as e:
            logger.error(f"Failed to create review: {e}")
            return None

    def create_comment(
        self,
        owner: str,
        repo: str,
        pr_number: int,
        commit_sha: str,
        path: str,
        line: int,
        body: str,
        side: str = 'RIGHT',
    ) -> Optional[Dict[str, Any]]:
        """Create a single review comment.

        Args:
            owner: Repository owner
            repo: Repository name
            pr_number: Pull request number
            commit_sha: SHA of the commit
            path: File path
            line: Line number
            body: Comment body
            side: Which side of the diff (LEFT or RIGHT)

        Returns:
            Comment response if successful, None otherwise
        """
        try:
            return self._post(
                f"/repos/{owner}/{repo}/pulls/{pr_number}/comments",
                {
                    'path': path,
                    'line': line,
                    'side': side,
                    'body': body,
                    'commit_id': commit_sha,
                },
            )
        except GitHubAPIError as e:
            logger.error(f"Failed to create comment on {path}:{line}: {e}")
            return None

    def add_reaction(
        self,
        owner: str,
        repo: str,
        comment_id: int,
        reaction: str,
    ) -> bool:
        """Add a reaction to a review comment.

        This is used to seed thumbs up/down reactions so users can easily
        click to vote on whether a finding is valid or a false positive.

        Args:
            owner: Repository owner
            repo: Repository name
            comment_id: ID of the comment
            reaction: Reaction type ('+1', '-1', 'laugh', 'confused', 'heart', 'hooray', 'rocket', 'eyes')

        Returns:
            True if successful, False otherwise
        """
        try:
            self._post(
                f"/repos/{owner}/{repo}/pulls/comments/{comment_id}/reactions",
                {'content': reaction},
            )
            return True
        except GitHubAPIError as e:
            logger.warning(f"Failed to add {reaction} reaction: {e}")
            return False


def get_github_client(
    token: Optional[str] = None,
    api_url: Optional[str] = None,
) -> GitHubClient:
    """Convenience function to get a configured GitHub client.

    Args:
        token: Optional GitHub token (reads from env if not provided)
        api_url: Optional API URL for GitHub Enterprise

    Returns:
        Configured GitHubClient instance
    """
    return GitHubClient(token=token, api_url=api_url)
